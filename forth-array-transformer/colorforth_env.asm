; ═══════════════════════════════════════════════════════════════════════════
; PART II — COLORFORTH ENVIRONMENT
;
; ColorForth's defining feature: text COLOR carries compiler semantics.
; WHITE — comment (skipped by compiler)
; RED — starts a new definition (like ":" in Forth)
; GREEN — compiled into the current definition
; YELLOW — executed immediately during compilation
; BLUE — display control (cr, indent, palette shifts)
;
; Source is stored in 1KB blocks (16 lines x 64 chars). Each character
; carries a parallel color tag. The environment can run hosted under
; Linux or boot bare-metal via the stub in Section 37.
; ═══════════════════════════════════════════════════════════════════════════

