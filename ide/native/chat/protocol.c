/*
 * Sovereign IDE — IPC Protocol
 * CRC32 checksum for frame validation.
 */

#include "protocol.h"

uint32_t protocol_checksum(const uint8_t *data, size_t len) {
    uint32_t crc = 0xFFFFFFFF;
    for (size_t i = 0; i < len; i++) {
        crc ^= data[i];
        for (int j = 0; j < 8; j++) {
            crc = (crc >> 1) ^ (0xEDB88320 & -(crc & 1));
        }
    }
    return ~crc;
}
